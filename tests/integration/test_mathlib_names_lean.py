"""Real Lean: theorems written with pl.mathlib names only (no module paths anywhere)."""

from __future__ import annotations

import pytest

import pyleanx as pl

pytestmark = pytest.mark.lean


def test_mathlib_names_resolve_to_importable_modules(lean_project):
    M = pl.mathlib
    x, y = pl.symbols("x y", pl.Real)
    n, m = pl.symbols("n m", pl.Nat)
    V = M.EuclideanSpace(pl.Real, pl.Fin(3))
    c, v = pl.var("c", pl.Real), pl.var("v", V)
    thms = [
        pl.Theorem("mn_sqrt_nonneg", [x], conclusion=pl.Le(0, M.Real.sqrt(x)),
                   proof=pl.exact(M.Real.sqrt_nonneg(x))),
        pl.Theorem("mn_abs_add", [x, y], conclusion=abs(x + y) <= abs(x) + abs(y),
                   proof=pl.exact(M.abs_add_le(x, y))),  # name generated by @[to_additive]
        pl.Theorem("mn_core", [n, m], conclusion=n + m == m + n,
                   proof=pl.exact(M.Nat.add_comm(n, m))),  # Lean core: no import
        pl.Theorem("mn_norm_smul", [c, v],
                   conclusion=pl.norm(pl.smul(c, v)) == pl.norm(c) * pl.norm(v),
                   proof=pl.exact(M.norm_smul(c, v))),
        pl.Theorem("mn_sum_odd", [n],
                   conclusion=pl.sum(M.Finset.range(n), lambda i: 2 * i + 1, sort=pl.Nat) == n**2,
                   proof=pl.induction("n", zero=pl.simp(),
                                      succ=pl.rw(M.Finset.sum_range_succ, "ih") >> pl.ring())),
        pl.Theorem("mn_exp_bound", [x], conclusion=x + 1 <= M.Real.exp(x),
                   proof=pl.exact(M.Real.add_one_le_exp(x))),
    ]
    for t in thms:
        assert "import Mathlib\n" not in t.to_lean()  # minimal, resolved imports
    results = pl.verify_all(thms, project=lean_project, timeout=1800)
    for r in results:
        print(r.summary())
    assert all(r.verified for r in results), [r.theorem for r in results if not r.verified]
