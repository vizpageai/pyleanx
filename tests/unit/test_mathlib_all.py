"""pl.mathlib: every Lean/Mathlib name without module paths (no Lean needed)."""

from __future__ import annotations

import pytest

import pyleanx as pl
from pyleanx import mathlib as M
from pyleanx.mathlib_index import _additive_name, scan_file

SAMPLE = """/-
Copyright … theorem fake_in_comment
-/
import Mathlib.Foo

namespace Real

/-- doc: theorem fake_in_doc -/
theorem sqrt_nonneg (x : ℝ) : 0 ≤ √x := by
  positivity

@[simp] lemma sq_sqrt (h : 0 ≤ a) : √a ^ 2 = a := by sorry

private theorem hidden : True := trivial

protected noncomputable def pi' : ℝ := 3

theorem _root_.global_one : 1 = 1 := rfl

section Inner
variable {x : ℝ}
lemma in_section : True := trivial
end Inner

end Real

@[to_additive] theorem Finset.prod_range_succ (f : ℕ → M) : True := trivial

@[to_additive (attr := simp) my_add_name]
theorem mul_thing : True := trivial

irreducible_def fderiv (f : E → F) : E := f

structure Point where
  x : ℝ

alias ⟨le_of_foo, foo_of_le⟩ := foo_iff
alias bar := baz
instance : Inhabited Point := ⟨⟨0⟩⟩
"""


def test_scanner_finds_declarations_and_namespaces():
    found = dict(scan_file(SAMPLE))
    assert found["Real.sqrt_nonneg"] == "theorem" and found["Real.sq_sqrt"] == "theorem"
    assert found["Real.pi'"] == "def" and found["global_one"] == "theorem"
    assert found["Real.in_section"] == "theorem"
    assert found["Finset.prod_range_succ"] == "theorem"
    assert found["Finset.sum_range_succ"] == "theorem"  # generated by @[to_additive]
    assert found["my_add_name"] == "theorem"  # explicit additive name
    assert found["fderiv"] == "def" and found["Point"] == "type"
    assert found["le_of_foo"] == found["foo_of_le"] == found["bar"] == "theorem"
    for absent in ("fake_in_comment", "fake_in_doc", "Real.hidden"):
        assert absent not in found


def test_additive_names():
    assert _additive_name("Finset.prod_range_succ") == "Finset.sum_range_succ"
    assert _additive_name("mabs_mul_le") == "abs_add_le"
    assert _additive_name("inv_mul_cancel") == "neg_add_cancel"


