def test_any_name_resolves_with_its_module(fake_index):
    lemma = pl.mathlib.Real.sqrt_nonneg
    assert isinstance(lemma, pl.proofs.Name) and lemma.imports == ("Mathlib.Analysis.Real.Sqrt",)
    assert pl.mathlib.Nat.add_comm.imports == ()  # Lean core: nothing to import
    x = pl.var("x", pl.Real)
    t = pl.Theorem("t", [x], conclusion=pl.Le(0, pl.mathlib.Real.sqrt(x)),
                   proof=pl.exact(pl.mathlib.Real.sqrt_nonneg(x)))
    src = t.to_lean()
    assert "import Mathlib.Analysis.Real.Sqrt" in src and "exact Real.sqrt_nonneg x" in src
    assert "0 ≤ Real.sqrt x" in src


def test_types_from_mathlib_work_as_sorts(fake_index):
    V = pl.mathlib.EuclideanSpace(pl.Real, pl.Fin(3))
    v = pl.var("v", V)
    assert v.sort.lean == "EuclideanSpace Real (Fin 3)"
    assert "Mathlib.Analysis.InnerProductSpace.PiL2" in v.sort.imports
    r = pl.var("r", pl.mathlib.Real)  # a namespace that is also a type
    assert r.sort.lean == "Real"


def test_curated_names_and_pl_ref_still_work(fake_index):
    assert pl.mathlib.mul_pos.name == "mul_pos"  # hand-written entry, unchanged
    ref = pl.ref("sq_nonneg", imports=["Mathlib.Algebra.Order.Ring.Unbundled.Basic"])
    assert ref == pl.mathlib.sq_nonneg


def test_unknown_names_suggest_alternatives(fake_index):
    with pytest.raises(AttributeError, match="sqrt_le_sqrt"):
        pl.mathlib.Real.sqrt_le_sqrtt  # noqa: B018
    assert M.find("Real.sqrt") == ("Mathlib.Analysis.Real.Sqrt", "def")
    assert M.find("nope") is None
    assert M.search("sqrt le")[0] == "Real.sqrt_le_sqrt"
    assert "sqrt" in dir(pl.mathlib.Real)
